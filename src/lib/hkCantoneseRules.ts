export type HkTermCategory =
  | '簡體字'
  | '內地用語'
  | '台灣用語'
  | '粵語口語'
  | '港式用詞';

export interface HkTermRule {
  /** 穩定 id；UI 的「已核對」與測試都用它 */
  id: string;
  /** 非港式寫法；可放多個變體（含簡體） */
  from: string[];
  /** 香港書面語（口語規則則是口語目標） */
  written: string;
  /** 口語版寫法；省略時：粵語口語規則用 from[0]，其餘用 written */
  colloquial?: string;
  category: HkTermCategory;
  note?: string;
  /** true = 只阻擋短規則，不輸出、不進替換表 */
  protect?: boolean;
}

