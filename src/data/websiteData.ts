export let allArticles: (Article & { __sampleData: true })[] = [];

// Many-to-many junction table
export let websiteArticles: WebsiteArticle[] = [];

// Helper functions for many-to-many queries
export function getArticlesForWebsite(websiteId: string): Article[] {
  const articleIds = websiteArticles
    .filter(wa => wa.websiteProfileId === websiteId)
    .map(wa => wa.articleId);
  return allArticles.filter(a => articleIds.includes(a.id));
}

export function getWebsitesForArticle(articleId: string): WebsiteProfileFull[] {
  const websiteIds = websiteArticles
    .filter(wa => wa.articleId === articleId)
    .map(wa => wa.websiteProfileId);
  return websiteProfiles.filter(ws => websiteIds.includes(ws.id));
}

export function addArticleToWebsite(websiteId: string, articleId: string, notes?: string): WebsiteArticle {
  const newEntry: WebsiteArticle = {
    id: `wa${Date.now()}`,
    websiteProfileId: websiteId,
    articleId: articleId,
    addedDate: new Date().toISOString().split('T')[0],
    notes,
  };
  websiteArticles = [...websiteArticles, newEntry];
  return newEntry;
}

export function removeArticleFromWebsite(websiteId: string, articleId: string): void {
  websiteArticles = websiteArticles.filter(
    wa => !(wa.websiteProfileId === websiteId && wa.articleId === articleId)
  );
}

export function addWebsiteToArticle(articleId: string, websiteId: string, notes?: string): WebsiteArticle {
  return addArticleToWebsite(websiteId, articleId, notes);
}

export function removeWebsiteFromArticle(articleId: string, websiteId: string): void {
  removeArticleFromWebsite(websiteId, articleId);
}

export function addNewArticle(article: Article): void {
  allArticles = [...allArticles, article];
}

export function addWebsiteProfile(website: WebsiteProfileFull): void {
  websiteProfiles.push(website);
}

export function updateWebsiteProfile(id: string, updates: Partial<WebsiteProfileFull>): void {
  const idx = websiteProfiles.findIndex(ws => ws.id === id);
  if (idx !== -1) {
    websiteProfiles[idx] = { ...websiteProfiles[idx], ...updates };
  }
}

